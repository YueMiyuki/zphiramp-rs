import io.netty.buffer.ByteBuf;
import io.netty.buffer.Unpooled;
import io.netty.handler.codec.DecoderException;
import top.rymc.phira.protocol.exception.BadVarIntException;
import top.rymc.phira.protocol.exception.NeedMoreDataException;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.zip.CRC32;

/** Shared helpers of the fixture generator: hex, outcome codes, the deterministic PRNG. */
final class Util {
    private Util() {}

    static String hex(byte[] b) {
        StringBuilder s = new StringBuilder(b.length * 2);
        for (byte x : b) {
            s.append(Character.forDigit((x >> 4) & 0xf, 16)).append(Character.forDigit(x & 0xf, 16));
        }
        return s.toString();
    }

    static byte[] unhex(String h) {
        byte[] b = new byte[h.length() / 2];
        for (int i = 0; i < b.length; i++) {
            b[i] = (byte) Integer.parseInt(h.substring(2 * i, 2 * i + 2), 16);
        }
        return b;
    }

    /** The readable bytes of {@code b}, without consuming them. */
    static byte[] bytes(ByteBuf b) {
        byte[] a = new byte[b.readableBytes()];
        b.getBytes(b.readerIndex(), a);
        return a;
    }

    static ByteBuf wrap(byte[] b) {
        return Unpooled.wrappedBuffer(b);
    }

    static String crc(byte[] b) {
        CRC32 c = new CRC32();
        c.update(b);
        return String.format("%08x", c.getValue());
    }

    static byte[] concat(byte[]... parts) {
        int n = 0;
        for (byte[] p : parts) n += p.length;
        byte[] r = new byte[n];
        int o = 0;
        for (byte[] p : parts) {
            System.arraycopy(p, 0, r, o, p.length);
            o += p.length;
        }
        return r;
    }

    /**
     * One-letter code of the failure, shared by the prefix and fuzz fixtures:
     * I index out of bounds, M out of memory (a huge declared list length: Java allocates the list
     * before reading any element, so whether it survives depends on the heap),
     * N NeedMoreDataException, V BadVarIntException, S bad string length, U unknown id,
     * A IllegalArgumentException (negative list capacity), X anything else.
     */
    static String code(Throwable t) {
        if (t instanceof OutOfMemoryError) return "M";
        if (t instanceof IndexOutOfBoundsException) return "I";
        if (t instanceof NeedMoreDataException) return "N";
        if (t instanceof BadVarIntException) return "V";
        if (t instanceof IllegalArgumentException) return "A";
        if (t instanceof DecoderException) {
            String m = String.valueOf(t.getMessage());
            if (m.startsWith("Bad string length")) return "S";
            if (m.startsWith("Unknown ")) return "U";
        }
        return "X:" + t.getClass().getName() + ":" + t.getMessage();
    }

    /** Class name (without package, with the nested-class separator kept) and message, for the error fixtures. */
    static String describe(Throwable t) {
        String msg = t instanceof IndexOutOfBoundsException || t instanceof OutOfMemoryError
                ? "-" : String.valueOf(t.getMessage());
        return t.getClass().getName() + "\t" + msg;
    }

    static final class Rng {
        long state;

        Rng(long seed) {
            state = seed;
        }

        /** splitmix64 */
        long next() {
            long z = (state += 0x9E3779B97F4A7C15L);
            z = (z ^ (z >>> 30)) * 0xBF58476D1CE4E5B9L;
            z = (z ^ (z >>> 27)) * 0x94D049BB133111EBL;
            return z ^ (z >>> 31);
        }

        int below(int n) {
            return (int) Long.remainderUnsigned(next(), n);
        }
    }

    static final class Out implements AutoCloseable {
        final List<String> lines = new ArrayList<>();
        final Path path;

        Out(Path dir, String name) {
            this.path = dir.resolve(name);
            lines.add("# generated by crates/protocol/tests/java/regen.sh from jphira-mp-protocol 2.2.1 on Netty 4.2.3.Final; do not edit by hand");
        }

        void line(String... cols) {
            lines.add(String.join("\t", cols));
        }

        void raw(String s) {
            lines.add(s);
        }

        @Override
        public void close() throws IOException {
            Files.write(path, (String.join("\n", lines) + "\n").getBytes(StandardCharsets.UTF_8));
            System.err.println("wrote " + path.getFileName() + " (" + lines.size() + " lines)");
        }
    }
}
